"""Generate databricks/resources/*.yml: one SF10 TPC-DI job per compute config.
Task graph comes from serverless_job_template.json (24 notebooks + 1 condition).
Run: python3 scripts/gen_resources.py
"""
import copy, json, pathlib
import yaml

root = pathlib.Path(__file__).parent.parent
tpl = json.load(open(root / "scripts/serverless_job_template.json"))
SF = "sf10"
RES = {"sql_warehouses": {}, "clusters": {}, "jobs": {}}


def job(name, schema, wh=None, perf=None, cluster=None, serverless_id=None, ap=None):
    j = copy.deepcopy(tpl)
    j["name"] = name
    j["tags"] = {"project": "etl-benchmark", "bench_config": schema, "scale_factor": SF}
    j["description"] = f"TPC-DI derived ETL, single batch, {SF}, config {schema}."
    for p in j["parameters"]:
        if p["name"] == "wh_db":
            p["default"] = f"etl_benchmark_{schema}"
    if perf:
        j["performance_target"] = perf
    if serverless_id:
        j["job_clusters"] = [{"job_cluster_key": "compute", "serverless_compute": {"policy_id": serverless_id}}]
    elif cluster:
        j["job_clusters"] = [{"job_cluster_key": "compute", "new_cluster": cluster}]
    for t in j["tasks"]:
        nb = t.get("notebook_task")
        if not nb:
            continue
        if serverless_id or cluster:
            t["job_cluster_key"] = "compute"
        if ap:
            t["existing_cluster_id"] = "${resources.clusters.%s.id}" % ap
        if wh:
            nb["warehouse_id"] = "${resources.sql_warehouses.%s.id}" % wh
    return j


def add_job(key, **kw):
    RES["jobs"][f"{key}_{SF}"] = job(f"etl-benchmark-{key}-{SF}", key, **kw)


# ---- SQL warehouses (serverless Pro, defaults otherwise) ----
for key, size in {"wh_large": "Large"}.items():
    RES["sql_warehouses"][f"{key}"] = {
        "name": f"etl-benchmark-{key}-{SF}", "cluster_size": size,
        "warehouse_type": "PRO", "enable_serverless_compute": True, "auto_stop_mins": 10}
    add_job(key, wh=key)

# ---- serverless jobs: no size ----
add_job("srv_optimized", perf="PERFORMANCE_OPTIMIZED")
add_job("srv_standard", perf="STANDARD")

# ---- serverless jobs: rate limit size. Compute objects are made in the UI
# (Compute > Serverless > Create); IDs go in scripts/serverless_ids.json ----
ids_file = root / "scripts/serverless_ids.json"
ids = json.load(open(ids_file)) if ids_file.exists() else {}
for size in ("small", "medium", "large"):
    if ids.get(size):
        add_job(f"srv_{size}", serverless_id=ids[size])

# ---- classic compute: m8gd, DBR 17.3, driver = worker node type (default) ----
def cluster(node, engine="PHOTON", spot=False, min_w=1, max_w=8):
    c = {"spark_version": "17.3.x-scala2.13", "node_type_id": f"m8gd.{node}",
         "runtime_engine": engine, "data_security_mode": "SINGLE_USER",
         "autoscale": {"min_workers": min_w, "max_workers": max_w}}
    if spot:
        c["aws_attributes"] = {"availability": "SPOT_WITH_FALLBACK"}
    return c


# three sizes, standard autoscale 1 to 8 workers
for node in ("xlarge", "2xlarge", "8xlarge"):
    add_job(f"jc_{node}", cluster=cluster(node))

# experiments at 2xlarge (all-purpose cluster lives here)
c = cluster("2xlarge")
c.update({"cluster_name": "etl-benchmark-ap_2xlarge", "autotermination_minutes": 10})
RES["clusters"]["ap_2xlarge"] = c
add_job("ap_2xlarge", ap="ap_2xlarge")

# extras on 2xlarge (same 1 to 8 autoscale unless stated). Spot applies to workers only.
add_job("jc_2xlarge_spot", cluster=cluster("2xlarge", spot=True))
add_job("jc_2xlarge_nophoton", cluster=cluster("2xlarge", engine="STANDARD"))
add_job("jc_2xlarge_min2", cluster=cluster("2xlarge", min_w=2, max_w=8))

out = {"resources": {k: v for k, v in RES.items() if v}}
(root / "single_batch/benchmark_sf10.yml").write_text(
    "# GENERATED by scripts/gen_resources.py. Edit the script, not this file.\n"
    + yaml.safe_dump(out, sort_keys=False, width=200))
print("ok")

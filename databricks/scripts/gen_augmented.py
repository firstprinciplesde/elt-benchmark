"""Generate resources/augmented_sf10.yml: ONE job per compute config.

Each job = a full load (the repo's setup notebook clones the staged historical
tables) followed by 29 simulated days, one after another, as plain tasks.
Day tasks come from augmented_template.json (the repo's 17-task daily job).
Run: python3 scripts/gen_augmented.py
"""
import copy, datetime as dt, json, pathlib
import yaml

root = pathlib.Path(__file__).parent.parent
tpl = json.load(open(root / "scripts/augmented_template.json"))
SF, DAYS, START = "sf10", 29, dt.date(2016, 7, 6)


def classic(node, engine="PHOTON", spot=False, min_w=1, max_w=8):
    c = {"spark_version": "17.3.x-scala2.13", "node_type_id": f"m8gd.{node}",
         "runtime_engine": engine, "data_security_mode": "SINGLE_USER",
         "autoscale": {"min_workers": min_w, "max_workers": max_w}}
    if spot:
        c["aws_attributes"] = {"availability": "SPOT_WITH_FALLBACK"}
    return c


# key: (performance_target, classic cluster spec). No cluster = serverless.
CONFIGS = {
    "serverless_standard": ("STANDARD", None),
    "serverless_optimized": ("PERFORMANCE_OPTIMIZED", None),
    "jc_xlarge": (None, classic("xlarge")),
    "jc_2xlarge": (None, classic("2xlarge")),
    "jc_8xlarge": (None, classic("8xlarge")),
    "jc_2xlarge_spot": (None, classic("2xlarge", spot=True)),
    "jc_2xlarge_nophoton": (None, classic("2xlarge", engine="STANDARD")),
    "jc_2xlarge_min2": (None, classic("2xlarge", min_w=2)),
}


def build(key, perf, cluster):
    tasks = []
    full = copy.deepcopy(tpl["setup"])
    full["task_key"] = "full_load"
    tasks.append(full)

    inner = {t["task_key"] for t in tpl["day"]}
    needed = {d["task_key"] for t in tpl["day"] for d in t.get("depends_on", [])}
    terminal = sorted(inner - needed)

    prev = ["full_load"]
    for n in range(1, DAYS + 1):
        date = (START + dt.timedelta(days=n - 1)).isoformat()
        for t in tpl["day"]:
            t = json.loads(json.dumps(t).replace("{{job.parameters.batch_date}}", date))
            t["task_key"] = f"{t['task_key']}_d{n:02d}"
            deps = [{"task_key": f"{d['task_key']}_d{n:02d}"} for d in t.get("depends_on", [])]
            t["depends_on"] = deps or [{"task_key": k} for k in prev]
            tasks.append(t)
        prev = [f"{k}_d{n:02d}" for k in terminal]

    tasks.append({"task_key": "delete_when_finished", "run_if": "ALL_DONE",
                  "depends_on": [{"task_key": k} for k in prev],
                  "condition_task": {"op": "EQUAL_TO", "left": "{{job.parameters.delete_tables_when_finished}}", "right": "TRUE"}})
    clean = copy.deepcopy(tpl["cleanup"])
    clean["depends_on"] = [{"task_key": "delete_when_finished", "outcome": "true"}]
    tasks.append(clean)

    if cluster:
        for t in tasks:
            if "notebook_task" in t:
                t["job_cluster_key"] = "compute"

    params = copy.deepcopy(tpl["parameters"])
    for p in params:
        if p["name"] == "wh_db":
            p["default"] = f"etl_benchmark_aug_{key}"
        if p["name"] == "incremental_batches_to_run":
            p["default"] = str(DAYS)
    job = {"name": f"etl-benchmark-aug-{key}-{SF}", "max_concurrent_runs": 1, "queue": {"enabled": True},
           "tags": {"project": "etl-benchmark", "config": key, "scale_factor": SF, "days": str(DAYS)},
           "parameters": params, "tasks": tasks}
    if perf:
        job["performance_target"] = perf
    if cluster:
        job["job_clusters"] = [{"job_cluster_key": "compute", "new_cluster": cluster}]
    return job


out = {"resources": {"jobs": {f"aug_{k}_{SF}": build(k, *v) for k, v in CONFIGS.items()}}}
(root / "resources/augmented_sf10.yml").write_text(
    "# GENERATED by scripts/gen_augmented.py. Edit the script, not this file.\n"
    + yaml.safe_dump(out, sort_keys=False, width=200))
print(len(out["resources"]["jobs"]), "jobs,", len(tpl["day"]) * DAYS + 3, "tasks each")
